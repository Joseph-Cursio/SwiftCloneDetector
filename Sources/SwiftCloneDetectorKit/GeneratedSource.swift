//  GeneratedSource.swift
//  SwiftCloneDetectorKit
//
//  Recognising machine-written files from the marker their generator leaves in
//  the header, so a clone report is not dominated by duplication nobody wrote.
//

/// Whether a source file was written by a code generator.
///
/// Generated code is duplicated by construction — a protobuf plugin emits the
/// same accessor shape for every field, a template emits the same test body for
/// every case — so it clusters heavily and none of it is actionable. In one
/// corpus scan `scip.pb.swift` carried 23 clone classes, more than any
/// hand-written file, and crowded out everything worth reading.
///
/// The test is the marker the generator writes into the file header. Every
/// generator observed in this corpus states one within the first few lines:
///
/// ```
/// // DO NOT EDIT.
/// // Generated by the Swift generator plugin for the protocol buffer compiler.
/// // GENERATED by Scripts/generate_rule_history.py — do not edit by hand.
/// // Auto-generated by `swift-infer convert-counterexample` — do not edit.
/// // Generated using Sourcery 2.0
/// ```
public enum GeneratedSource {
    /// Header phrases that mean "a program wrote this", lowercased for matching.
    ///
    /// `do not edit` alone is enough: a hand-written file carrying it in its
    /// header is saying the same thing — that its contents are derived from
    /// somewhere else and are not the place to make a change.
    private static let markers = [
        "do not edit",
        "@generated",
        "generated by",
        "generated using"
    ]

    /// How far into the file to look. A marker below a long licence banner is
    /// still a header marker; a mention of "generated by" in the body is not.
    private static let headerLineLimit = 40

    /// Whether `text` carries a generator's marker in its leading comments.
    ///
    /// Scanning stops at the first line of actual code, so only the header is
    /// considered — and stops after ``headerLineLimit`` lines, so the cost does
    /// not scale with a large generated file.
    public static func isGenerated(_ text: String) -> Bool {
        let lines = text.split(
            separator: "\n",
            maxSplits: headerLineLimit,
            omittingEmptySubsequences: false
        )
        for line in lines.prefix(headerLineLimit) {
            let trimmed = line.drop { $0 == " " || $0 == "\t" || $0 == "\r" }
            if trimmed.isEmpty {
                continue
            }
            guard isCommentOrShebang(trimmed) else {
                return false
            }
            let lowered = trimmed.lowercased()
            if markers.contains(where: lowered.contains) {
                return true
            }
        }
        return false
    }

    /// Lines a header may contain before the code starts: line and block
    /// comments, a continuation line of a block comment, and a shebang.
    private static func isCommentOrShebang(_ line: Substring) -> Bool {
        line.hasPrefix("//") || line.hasPrefix("/*") || line.hasPrefix("*") || line.hasPrefix("#!")
    }
}

public extension SourceInput {
    /// Whether this file was written by a code generator. See ``GeneratedSource``.
    var isGenerated: Bool {
        GeneratedSource.isGenerated(text)
    }
}
