//
//  GeneratedSourceTests.swift
//  SwiftCloneDetectorKitTests
//
//  The header shapes are verbatim from the generators found in the corpus this
//  filter was written for, so a generator changing its banner breaks a test
//  rather than quietly re-admitting 23 clone classes of protobuf accessors.
//

@testable import SwiftCloneDetectorKit
import Testing

@Suite("GeneratedSource")
struct GeneratedSourceTests {
    @Test(
        "recognises the generators in the corpus",
        arguments: [
            // protoc — marker on line 1, attribution four lines below.
            """
            // DO NOT EDIT.
            // swift-format-ignore-file
            // swiftlint:disable all
            //
            // Generated by the Swift generator plugin for the protocol buffer compiler.
            // Source: scip.proto
            import Foundation
            """,
            // A project script, under the file's ordinary Xcode banner.
            """
            //
            //  RuleHistory+Generated.swift
            //  SwiftFormatRuleStudio
            //
            //  GENERATED by Scripts/generate_rule_history.py — do not edit by hand.
            //
            import Foundation
            """,
            // A SwiftPM plugin.
            """
            // GENERATED by PropertyLawDiscoveryPlugin — DO NOT EDIT outside
            // `// property-law-suppress: <protocol>_<TypeName>` markers.
            import Testing
            """,
            // swift-infer's counterexample converter.
            """
            // Auto-generated by `swift-infer convert-counterexample` — do not edit.
            // Counterexample for: idempotence / YAMLConfigurationEngine
            import Testing
            """,
            // A generated manifest, below the tools-version line.
            """
            // swift-tools-version: 6.1
            // V1.42.C.3 auto-generated. Do not edit.
            import PackageDescription
            """,
            // Sourcery and SwiftGen, which say only that they generated it.
            """
            // Generated using Sourcery 2.0 — https://github.com/krzysztofzablocki/Sourcery
            import Foundation
            """
        ]
    )
    func recognisesGenerators(header: String) {
        #expect(GeneratedSource.isGenerated(header))
    }

    @Test("leaves hand-written files alone")
    func ignoresHandWritten() {
        let source = """
        //
        //  VaultManager.swift
        //  SwiftMarkdownWiki
        //
        //  Owns the vault's file tree and the index built from it.
        //

        import Foundation

        struct VaultManager {
            let root: URL
        }
        """
        #expect(GeneratedSource.isGenerated(source) == false)
    }

    // The marker has to be a header marker. A file that merely *discusses*
    // generated code — this project's own docs and rules do — is hand-written.
    @Test("a marker in the body is not a header marker")
    func ignoresMarkerBelowTheCode() {
        let source = """
        import Foundation

        /// Skip files a generator wrote: they always say "do not edit".
        func isGenerated(_ text: String) -> Bool {
            text.contains("Generated by")
        }
        """
        #expect(GeneratedSource.isGenerated(source) == false)
    }

    @Test("an empty file is not generated")
    func ignoresEmpty() {
        #expect(GeneratedSource.isGenerated("") == false)
    }

    @Test("SourceInput answers for its own text")
    func sourceInputForwards() {
        let generated = SourceInput(path: "a.pb.swift", text: "// DO NOT EDIT.\nimport Foundation")
        let handWritten = SourceInput(path: "b.swift", text: "import Foundation")
        #expect(generated.isGenerated)
        #expect(handWritten.isGenerated == false)
    }
}
